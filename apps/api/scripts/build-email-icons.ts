/**
 * Turns the SVG icons in assets/email into PNGs embedded in src/services/emailIcons.ts.
 * Gmail and Outlook do not show SVG, so emails attach these PNGs inline.
 * Run after editing an icon: npm run email-icons -w @wellpath/api
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";

const DIR = "assets/email";
const SIZE = 192; // shown at 96px, so it stays sharp on high-density screens

const icons = readdirSync(DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((file) => {
    const png = new Resvg(readFileSync(`${DIR}/${file}`), { fitTo: { mode: "width", value: SIZE } }).render().asPng();
    writeFileSync(`${DIR}/${file.replace(".svg", ".png")}`, png); // for previewing; not used at runtime
    console.log(`${file}: ${(png.length / 1024).toFixed(1)} KB`);
    return [file.replace(".svg", ""), png.toString("base64")] as const;
  });

const body = icons.map(([name, b64]) => `  "${name}": "${b64}",`).join("\n");
writeFileSync(
  "src/services/emailIcons.ts",
  `/** Generated by scripts/build-email-icons.ts from assets/email/*.svg. Do not edit by hand. */\nexport const EMAIL_ICONS = {\n${body}\n} as const;\n\nexport type EmailIcon = keyof typeof EMAIL_ICONS;\n`,
);
console.log("Wrote src/services/emailIcons.ts");
